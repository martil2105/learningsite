  <h3 class="body-header">Where this leaves the triangle</h3>
  <p>
    Economists have long debated whether the deadweight losses from market
    interventions are big enough to worry about, and the triangle on its own
    suggests they usually aren't. Once we also count who ends up with the
    goods, the picture changes in four ways.
  </p>
  <p>
    First, the triangle really is small. Trade stops closest to the margin,
    where the gains from each trade are thinnest, so the loss from the missing
    trades grows with the square of the cut. A cut of <em>d</em> costs only
    <em>d</em>² of the total surplus, so a 10% cut costs just 1% of the gains
    from trade.
  </p>
  <p>
    Second, rationing is first order. When a shortage is resolved by queues,
    lotteries or bureaucracy rather than by prices, the units no longer go to
    the buyers who value them most. That misallocation loss grows as
    <em>d</em>(1 − <em>d</em>), and it's bigger than the triangle for every cut
    under 50%. At a 10% cut, rationing costs nine times as much as the
    triangle.
  </p>
  <p>
    Third, the total loss equals the cut itself. In any linear market with
    random rationing, the two losses add up exactly:
    <em>d</em>² + <em>d</em>(1 − <em>d</em>) = <em>d</em>. So a 27% shortfall
    in quantity loses exactly 27% of the total surplus.
  </p>
  <p>
    And finally, the policy instrument decides the cost. Holding quantity down
    with a quota costs <em>d</em>², while holding it down with a price ceiling
    costs <em>d</em>, which is 1/<em>d</em> times as much. At a 10% cut, the
    price ceiling is ten times as costly as the quota.
  </p>
