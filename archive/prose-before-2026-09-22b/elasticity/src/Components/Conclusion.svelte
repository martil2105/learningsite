  <h3 class="body-header">Where this leaves elasticity</h3>
  <p>
    We usually meet elasticity as a sensitivity coefficient, a number attached
    to a good. We've seen that it's better thought of as geometry, in three
    ways.
  </p>
  <p>
    First, it isn't a property of a good. On a single straight demand curve,
    elasticity takes every value from zero to infinity: at p = 5 the good is
    very inelastic, with |ε| = 0.087, and at p = 60 the same good is very
    elastic, with |ε| = 24.0. Calling something "an elastic good" mistakes a
    point for the whole curve.
  </p>
  <p>
    Second, it's a ratio of two lengths. On any smooth demand curve, a point
    cuts its own tangent into an upper piece, which runs to the quantity axis,
    and a lower piece, which runs to the price axis, and the elasticity is
    exactly the upper length divided by the lower one. When the two pieces are
    equal, the elasticity is exactly one and revenue is at its maximum.
  </p>
  <p>
    And third, the two-point formulas quietly commit to a curve. There's no way
    to calculate an elasticity from two observations without choosing a model:
    the midpoint formula is exactly the point elasticity of a straight line, and
    the log-difference formula is exactly the exponent of a constant-elasticity
    curve. So choosing a formula means choosing a demand curve.
  </p>
