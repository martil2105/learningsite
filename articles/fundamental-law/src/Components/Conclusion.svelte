  <h3 class="body-header">Breadth with a ceiling</h3>
  <p>
    Grinold's law splits skill into two parts, how good each forecast is and how many independent forecasts we make, and the second part
    grows without limit. That holds when the only thing that changes from month to month is which stocks happen to beat their forecasts.
  </p>
  <p>
    Once a signal's skill itself moves, each extra stock adds less, and the ratio stops at the IC divided by its swing. A manager with a
    strong signal on a few stocks barely notices. A manager with a faint signal on many stocks loses much of her breadth, and her risk model
    won't tell her so.
