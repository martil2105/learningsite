  <h3 class="body-header">Back to checking cells</h3>
  <p>
    Checking cells isn't wrong, and in three two-by-two games out of four, it
    gives the whole answer. What it hides is that it only searches the outcomes
    where both players are predictable, and that search comes up empty often
    enough to matter. When it does, the equilibrium is still there. It's a pair
    of frequencies rather than a cell, and it has a property the cell version
    never shows us: each player's behaviour is written in the other player's
    payoffs.
  </p>
  <p>
    That's worth carrying over to equilibria in general. An equilibrium
    describes a whole system, not each person in it on their own. It's tempting
    to work out what each player wants and add the answers up. Our trader and
    risk desk show why that doesn't work: what each of them does is set by what
    the other one wants.
  </p>
