  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      CORE Econ (2023), <em>The Economy 2.0: Microeconomics</em>, Unit 4,
      sections 4.2, 4.3 and 4.5. A free introduction to best responses, Nash
      equilibrium and the Pareto criterion, and where many readers will have met
      the dots-and-circles way of checking cells. It doesn't cover mixed
      strategies, which is a reasonable choice for a first course, and this
      article starts where it stops.
    </li>
    <li>
      Nash, J. F. (1950), "Equilibrium points in n-person games",
      <em>Proceedings of the National Academy of Sciences</em>, 36(1), 48–49.
      The existence theorem: once mixed strategies are allowed, every finite
      game has an equilibrium.
    </li>
    <li>
      The result that a random game has one surviving cell on average, with a
      Poisson(1) limit as the game grows, is a standard one in the literature on
      random games.
    </li>
    <li>
      The finding that the certainty of being caught matters more than the
      severity of the punishment is a long-running theme in the empirical
      literature on crime, and our summary of it is deliberately broad.
    </li>
  </ul>
  <p>Related articles on this site:</p>
  <ul class="resources-list">
    <li>
      <a href="../bargaining-and-the-surplus/">Bargaining and the surplus</a>,
      on how alternating offers pick one split of a surplus, and why the other
      side's impatience matters most.
    </li>
    <li>
      <a href="../cartels-and-the-prisoners-dilemma/">Cartels and the
      prisoner's dilemma</a>, on a game where checking cells does find an
      answer, and on why cartels are hard to hold together.
    </li>
  </ul>
