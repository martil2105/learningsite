  <h3 class="body-header">A rate that isn't in the bond</h3>
  <p>
    A bond's yield to maturity is the one rate that prices all of its payments, and as a summary of the price it's exactly right. As a
    forecast of what we'll earn by holding on, it needs every coupon to be reinvested at that same rate, and on a long bond the reinvestment
    is most of the money.
  </p>
  <p>
    If the yield never moves, every bond earns it, whatever its coupon, so a premium bond's falling price is nothing to worry about. If rates
    move just after we buy, we earn the old yield on a share of the bond's life equal to its average wait over its maturity, and the new rate
    on the rest. Only a zero-coupon bond keeps its promise whatever happens to rates.
  </p>
