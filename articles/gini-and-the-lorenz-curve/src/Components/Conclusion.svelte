  <h3 class="body-header">What one number can and can't tell us</h3>
  <p>
    The Gini is a fair summary of a whole distribution, and it has a friendly
    meaning: the average gap between two people, over twice the mean income.
    What it can't tell us is where the inequality sits. When two Lorenz curves
    cross, any ranking of them rests on a choice about whose incomes count most,
    and the Gini makes that choice for us, by weighting people according to
    their rank.
  </p>
  <p>
    The same goes for a bank. A scorecard's Gini is built the same way, with
    defaulters in place of income, so two scorecards with the same Gini can
    behave quite differently at the cut-off where we actually make decisions.
    So when you're handed a Gini, whether it belongs to a country or to a model,
    it's worth asking to see the curve behind it.
  </p>
