  <h3 class="body-header">Where this leaves the fixed basket</h3>
  <p>
    A fixed basket does overstate how much more it costs to live as well as
    before, and first courses are right to say so. What they usually leave out
    is the size of it. The overstatement is nothing when prices move together,
    and it grows with the square of how far apart they move.
  </p>
  <p>
    They also leave out the most useful part. The elasticity that nobody can
    observe is recorded after all, in the basket people actually buy. The
    Fisher index uses it without ever having to name it, and that's why
    averaging two wrong answers gets us so close to the right one.
