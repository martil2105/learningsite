  <h3 class="body-header">Where the limit binds</h3>
  <p>
    Solving a small working life backwards, we found what Cocco, Gomes and Maenhout's paper leads us to expect. While a worker's pay is still to
    come, it acts like a bond, so her savings can hold as much stock as she's allowed, and the share falls as her savings grow. In our version
    that lasts for decades unless she's very cautious, and a looser limit only postpones the day it stops binding.
  </p>
  <p>
    What the limit costs depends on who she is. A bold worker whose pay has nothing to do with the market loses the most when she can't
    borrow, and a cautious one, or one whose pay moves with stocks, loses little. That's the case for leverage over a lifetime, and the next
    two articles look at it with the price of borrowing put back in.
  </p>
