  <h3 class="body-header">Two gaps in one number</h3>
  <p>
    Creation and redemption keep an ETF's price close to what its holdings are worth today, within what it costs an AP to trade them,
    and without the fund trading anything itself. The NAV is a different number, built from the holdings' last prices, and when they trade rarely it runs days behind.
  </p>
  <p>
    So a reported premium is two gaps added together, the price's and the NAV's. The price closes its own through arbitrage, and the NAV
    closes the other by catching up, a share of the way each day. When a bond ETF trades at a deep discount in a sell-off, the question
    worth asking is which of the two will move, and in our fund it's usually the NAV.
  </p>
