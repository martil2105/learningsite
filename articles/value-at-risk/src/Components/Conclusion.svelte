  <h3 class="body-header">One point, or the whole tail</h3>
  <p>
    Value at risk is a height on the curve of possible losses, read at one level. That makes it easy to explain, and it also makes it blind to
    what happens beyond that level. When losses come in lumps, spreading money over more positions can push a lump across the line, and the
    value at risk rises even as the real risk falls.
  </p>
