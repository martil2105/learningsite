  <h3 class="body-header">The horizon was never the reason</h3>
  <p>
    The old advice to hold more stocks when young turns out to be right for a different reason than the one usually given. It isn't that we
    have time to recover. It's that most of what a young worker owns is future pay, which behaves much like a bond, so her savings are a small
    slice of a portfolio that's already heavy in bonds. Merton's rule on the whole portfolio then asks her savings to carry many times their
    own value in stocks.
  </p>
  <p>
    Two things cut that down. If our pay moves with the market, it already holds stocks for us, and the extra shrinks or turns negative. And
    since we can't borrow dozens of times our savings, the rule runs into any limit for decades, so the real question for a young saver is how
    close to the limit to go, and how. The next articles look at the cost of borrowing and at spreading our exposure evenly across a life.
  </p>
