  <ul class="resources-list">
    <li>
      Bodie, Z., Merton, R. C. and Samuelson, W. F. (1992), "Labor supply flexibility and portfolio choice in a life cycle model",
      <em>Journal of Economic Dynamics and Control</em>, 16(3–4), 427–449. Future pay as part of wealth, and what flexible hours add.
    </li>
    <li>
      Viceira, L. M. (2001), "Optimal portfolio choice for long-horizon investors with nontradable labor income", <em>Journal of Finance</em>,
      56(2), 433–470. Risky pay that can't be sold, and how its link to the market changes the share.
    </li>
    <li>
      Cocco, J. F., Gomes, F. J. and Maenhout, P. J. (2005), "Consumption and portfolio choice over the life cycle", <em>Review of Financial
      Studies</em>, 18(2), 491–533. A full lifecycle model with a borrowing limit, where the young sit at 100% stocks.
    </li>
    <li>
      Campbell, J. Y. and Viceira, L. M. (2002), <em>Strategic Asset Allocation: Portfolio Choice for Long-Term Investors</em>, Oxford
      University Press. The textbook treatment, including labour income.
    </li>
