  <h3 class="body-header">Why the real chance drops out</h3>
  <p>
    When a share can only go up or down, a call can be copied exactly with shares and a loan, so its price is what the copy costs. That price
    can be written as an average payoff under the risk-neutral chance, which is a price in disguise rather than anyone's belief. Many small
    steps of the same trick give Black and Scholes's formula, zigzagging towards it as the steps shrink.
  </p>
  <p>
    The real chance of a rise still decides what the option is expected to earn, which is the share's extra return times the option's
    leverage. And it only drops out of the price because the copy is exact. Give the share a third branch, and the copy fails, arbitrage only
    bounds the price, and what investors believe and how they feel about risk come back in.
