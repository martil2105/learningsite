  <h3 class="body-header">A forward made of options</h3>
  <p>
    A European call minus a European put with the same strike and expiry pays the share price minus the strike, so it's a forward, and it
    costs what a forward costs whatever model we believe. Two models that disagree about every call and every put agree exactly on their
    difference, and a call and a put at the same strike always imply the same volatility.
  </p>
  <p>
    The useful direction is backwards. Option prices tell us the forward price the market is using, with its dividends and borrowing fees
    inside it, and if we use the wrong forward, calls and puts seem to disagree. When Palm's shares couldn't be borrowed in March 2000, its
    options priced a share for November 23% to 29% below the price it traded at. That wasn't parity failing. It was parity telling us what
    borrowing a Palm share was worth.
  </p>
