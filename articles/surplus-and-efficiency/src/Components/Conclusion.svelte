  <h3 class="body-header">Where this leaves the triangle</h3>
  <p>
    The deadweight loss triangle is right about what it measures. Trade stops
    closest to the margin, where each trade gains the least, so the loss from
    the missing trades really is small for small cuts. What the triangle leaves
    out is who ends up with the units that still trade. When a shortage is
    settled by queues or lotteries rather than by prices, that misallocation
    loss grows in proportion to the cut, and for any cut under half it's the
    bigger of the two.
  </p>
  <p>
    In our linear market, the two losses add up to the size of the cut itself.
    So what an output cut costs depends much more on how we enforce it than on
    how big it is: a quota costs d² of the total surplus, and a price ceiling
    that produces the same quantity costs d.
  </p>
