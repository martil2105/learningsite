  <h3 class="body-header">Sources and further reading</h3>
  <ul class="citation-list">
    <li>
      CORE Econ (2023), <em>The Economy 2.0: Microeconomics</em>, Unit 8,
      "Supply and demand: Price-taking and competitive markets". A free
      textbook treatment of competitive equilibrium.
    </li>
    <li>
      Working, E. J. (1927), "What Do Statistical 'Demand Curves' Show?",
      <em>The Quarterly Journal of Economics</em>, 41(2), 212–235. The paper
      that set out the identification problem in market data.
    </li>
    <li>
      Leamer, E. E. (1981), "Is It a Demand Curve, or Is It a Supply Curve?
      Partial Identification through Inequality Constraints",
      <em>The Review of Economics and Statistics</em>, 63(3), 319–327. The
      bracket from the forward and reverse regressions when the demand and
      supply shocks are uncorrelated.
    </li>
    <li>
      Gini, C. (1921), "Sull'interpolazione di una striscia bivariata",
      <em>Metron</em>, 1, 63–82; and Frisch, R. (1934), <em>Statistical
      Confluence Analysis by Means of Complete Regression Systems</em>. Early
      versions of the reverse-regression bounds, for variables measured with
      error.
    </li>
    <li>
      Leamer, E. E. (1978), <em>Specification Searches: Ad Hoc Inference with
      Nonexperimental Data</em>, John Wiley &amp; Sons. A longer treatment of
      bounds like these in econometrics.
    </li>
    <li>
      Klepper, S., and Leamer, E. E. (1984), "Consistent Sets of Estimates for
      Regressions with Errors in All Variables", <em>Econometrica</em>, 52(1),
      163–183. The same kind of bounds when every variable is measured with
      error.
    </li>
  </ul>
