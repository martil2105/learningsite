  <h3 class="body-header">Choosing an instrument</h3>
  <p>
    When we know the costs, a tax, a quota and a bargain are three routes to the
    same output, and they even move the same sum of money. What differs is who
    ends up holding it: the government, the plant or the town. That's a real
    difference, but it's about fairness rather than efficiency.
  </p>
  <p>
    Uncertainty changes that. Once we can't be sure of the plant's costs, the
    instruments stop being equivalent, and the better one is the one that lets
    the cheaper thing vary. If damage is flat, it costs little to let the
    quantity move, so a tax does better. If damage is steep, it's safer to hold
    the quantity still and let the price move, so a quota does better. So the
    next time you hear a tax and a cap argued over, it's worth asking which
    slope is steeper.
  </p>
