  <h3 class="body-header">One gap, three jobs</h3>
  <p>
    Priced as a growing stream of dividends, a share is worth next year's
    dividend divided by the gap between the discount rate and the growth rate.
    That gap does three jobs at once. It's the dividend yield, it sets the price
    per dollar of dividend, and turned upside down it's the share's duration,
    which puts a share with a small gap in the same league as a long government
    bond.
  </p>
  <p>
    Because so much of the value arrives decades from now, a small change in the
    discount rate moves the price a lot, and a rise hurts less than a fall helps.
    For anyone valuing a company, that's a reason for some humility: most of the
    number comes from assumptions about the distant future. The next step is to
    ask what the growth rate itself depends on, which is where price-to-earnings
    ratios come in.
  </p>
