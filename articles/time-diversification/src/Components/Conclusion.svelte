  <h3 class="body-header">Odds and depth</h3>
  <p>
    Holding stocks for longer does two things at once. It makes ending behind bonds less likely, because the median path's lead grows in a
    straight line while the noise grows like a square root. It also makes ending behind worse when it happens, because the noise in our money
    compounds. For the rare outcomes we most want to avoid, the second effect wins for decades.
  </p>
  <p>
    So "time is on your side" is true about odds and misleading about depth. When we hear it, it's worth asking which of the two someone
    means. The next two articles take the question further, first with a bet and then with the price of insurance.
