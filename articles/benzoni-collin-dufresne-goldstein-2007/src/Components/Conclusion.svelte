  <h3 class="body-header">Bond over a paycheck, stock over a career</h3>
  <p>
    Rebuilding the idea with pay that follows dividends with a lag, we found what the abstract of Benzoni, Collin-Dufresne and Goldstein's
    paper leads us to expect. Far-off paydays behave like stock and near ones like a bond, so a young worker's future pay is stock-like and an
    older worker's is not. That makes the share of savings in stocks small, or even negative, when we're young, and it rises and then falls
    with age.
  </p>
  <p>
    How far it swings depends on how quickly pay follows dividends. In our plan the young worker's share changes sign within half a year of
    half-life, which is a reason to be careful with any rule that treats future pay as a single number. The next two articles turn to what a
    life of borrowing would look like, and to what the loan costs.
