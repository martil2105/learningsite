  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Fernholz, R. (2002), <em>Stochastic Portfolio Theory</em>, Springer. Portfolios measured against the market, and the role of the
      market's concentration, which he called its diversity. The equal-weighted portfolio is one of his functionally generated portfolios.
    </li>
    <li>
      Fernholz, R. and Shay, B. (1982), "Stochastic portfolio theory and stock market equilibrium", <em>Journal of Finance</em>, 37(2),
      615–624. The growth rate of a rebalanced portfolio and why it can beat the market's.
    </li>
    <li>
      Booth, D. G. and Fama, E. F. (1992), "Diversification returns and asset contributions", <em>Financial Analysts Journal</em>, 48(3),
      26–32. The extra growth from rebalancing, which they called the diversification return.
    </li>
    <li>
      S&amp;P Dow Jones Indices, <em>Index Mathematics Methodology</em>. How an index's level and divisor are kept continuous through
      changes in its members and their shares.
    </li>
    <li>
      S&amp;P Dow Jones Indices, "FAQ: S&amp;P 500 Equal Weight Index". The index's quarterly rebalance back to equal weights.
    </li>
  </ul>
