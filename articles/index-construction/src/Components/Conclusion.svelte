  <h3 class="body-header">A gain and a concentration</h3>
  <p>
    A cap-weighted index never has to trade as prices move, and an equal-weighted one has to sell its winners and buy its losers every time
    it rebalances. The trading grows with the square root of how often it rebalances, and the gain it buys doesn't, so quarterly does as well
    as daily.
  </p>
  <p>
    The gap between the two indices is that gain plus the change in the cap-weighted index's concentration, exactly. When every stock has the
    same prospects, the two nearly cancel, because what one index earns by selling its winners the other earns by letting them run. When big
    firms can't keep growing faster than the rest, concentration stops rising and the equal-weighted index keeps most of its gain.
  </p>
