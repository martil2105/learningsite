  <h3 class="body-header">Two numbers</h3>
  <p>
    What we get from a daily-reset fund over any period comes down to two
    numbers: the index's return and its realised variance. The index's return,
    raised to the power L, compounds in our favour in a trend. The variance,
    times (L² − L)/2, drags us down every day the market moves. So in a flat,
    volatile year the drag wins and we lose money while the index goes nowhere,
    and in a smooth trend the compounding wins and we beat L times the index.
  </p>
  <p>
    Because that coefficient is symmetric about a half, inverse funds pay more
    drag than the leveraged funds they mirror. The same half of the variance is
    behind the gap between average and compound growth in the
    <a href="../compound-growth/">compound growth</a> article, and it comes back
    when we look at why diversification raises the growth of a portfolio.
  </p>
