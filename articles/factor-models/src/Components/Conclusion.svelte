  <h3 class="body-header">An alpha is a pair</h3>
  <p>
    An alpha belongs to an asset and a model together. When we add a factor, the alpha moves by minus the asset's loading on it times the
    factor's own alpha, exactly, so we can always say where an alpha went. Value's 4.5% disappears once the model pays for investment, and the
    low-beta shares' 2.5% disappears once it pays for profitability and investment.
  </p>
  <p>
    The same identity works the other way. An asset that leans against a factor with a positive alpha gains alpha when that factor joins the
    model, which is what happens to momentum when we add value. So a bigger model isn't a stricter test in every direction. It's a different
    question, and choosing it is a judgement about which returns we count as reward for risk.
