  <h3 class="body-header">Where this leaves free entry</h3>
  <p>
    Free entry really does pull the price down towards the lowest average cost,
    and in a big market it gets very close. What it can't do, except by luck,
    is get there exactly, because the market has to hold a whole number of
    firms. The last firm in makes a small profit, the next one would make a
    loss, and so entry stops a little early.
  </p>
  <p>
    That leaves us with a long-run supply curve shaped like a saw, whose teeth
    shrink as the market grows. It also leaves the market at most one firm
    short of the number a planner would choose, and never over it, which is a
    reassuring thing to know about perfect competition.
  </p>
