  <h3 class="body-header">Where this leaves cartels</h3>
  <p>
    The usual story says cartels fall apart because their members cheat, and
    that's part of the answer. Our model adds something that comes first. When a group of
    firms makes less, the firms outside it make more, so the cartel pays for
    the higher price and the outsiders gain more from it than the members do.
    Unless the cartel takes in almost the whole market, its members can end up no better
    off than before, or worse.
  </p>
  <p>
    It also shows why staying out is so tempting, and that's the prisoner's
    dilemma in our title: every firm would do well in a cartel of all of them,
    and each does better outside one. Competition authorities use the same
    logic against real cartels. A <span class="bold">leniency
    programme</span> offers immunity to the first member that reports its
    cartel, which gives every member a reason to come forward before the
    others do.
  </p>
