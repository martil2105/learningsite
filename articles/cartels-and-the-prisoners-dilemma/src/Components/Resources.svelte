  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Salant, S. W., Switzer, S. and Reynolds, R. J. (1983), "Losses from
      Horizontal Merger: The Effects of an Exogenous Change in Industry
      Structure on Cournot-Nash Equilibrium", <em>Quarterly Journal of
      Economics</em>, 98(2), 185–199. The paper this article follows: in a
      Cournot market, a merger or cartel can lower its members' profits unless
      it includes nearly every firm.
    </li>
    <li>
      Stigler, G. J. (1964), "A Theory of Oligopoly", <em>Journal of Political
      Economy</em>, 72(1), 44–61. A classic account of why cartels are hard to
      police, and how members can spot secret price cuts.
    </li>
    <li>
      Friedman, J. W. (1971), "A Non-cooperative Equilibrium for
      Supergames", <em>Review of Economic Studies</em>, 38(1), 1–12. How the
      threat of future punishment can hold a cartel together when the game
      repeats.
    </li>
    <li>
      Spagnolo, G. (2008), "Leniency and Whistleblowers in Antitrust", in
      P. Buccirossi (ed.), <em>Handbook of Antitrust Economics</em>, MIT
      Press. How leniency programmes use the prisoner's dilemma to break
      cartels up.
    </li>
  </ul>
