  <h3 class="body-header">A baseline, not a verdict</h3>
  <p>
    Solving a lifetime of choices backwards, Samuelson and Merton found that the last year's problem is every year's problem for an investor
    whose dislike of risk is in proportion to their wealth. The value of wealth keeps the same shape as it passes back through the years, so
    the best share never changes. Having time to recover isn't, on its own, a reason to hold more stock.
  </p>
  <p>
    The result is sharp because its assumptions are, and each one we loosened brought the horizon back. A floor made the young hold more,
    returns that revert did too, and a wage still to be earned does most of all. The next article takes the wage seriously.
