  <h3 class="body-header">Where this leaves elasticity</h3>
  <p>
    We usually meet elasticity as a number attached to a good. We've seen that
    it's better thought of as a number attached to a point on a curve. On one
    straight demand line it runs from nearly zero to very large, and at any
    point on any smooth curve, we can read it off as the ratio of the two
    pieces the point cuts from its tangent. Where those pieces are equal,
    revenue is at its peak.
  </p>
  <p>
    That also changes how we should read an elasticity computed from two
    observations. Each of the usual formulas assumes a curve between the two
    points, the midpoint formula a straight line and the log-difference formula
    a constant-elasticity curve, so choosing a formula means choosing a demand
    curve. For small price changes the choice hardly matters, and for large
    ones it's worth making on purpose.
  </p>
