  <h3 class="body-header">One number, three jobs</h3>
  <p>
    Duration is the average wait for a bond's money, and it's how far the price moves when the yield moves a little. It's also the one horizon at which a sudden move in rates can't leave us short of what the yield promised. The three are one fact seen from different sides: the price
    and the reinvestment pull on our money with strengths D and H, and they cancel when the two are equal.
  </p>
  <p>
    Convexity is what turns that cancellation into a small gain. It comes from how spread out the payments are, and in a market where every
    rate moved together it would be free. Real rates don't move together, and the market prices convexity into yields, so the gain at the
    bottom of the valley is mostly something we've already paid for.
