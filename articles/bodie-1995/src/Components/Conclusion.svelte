  <h3 class="body-header">A price, not a probability</h3>
  <p>
    Bodie turned a question about risk into a question about price. Insuring stocks against ending behind bonds costs more the longer the
    horizon, even though the chance of needing the insurance falls. That's because the price depends only on volatility and time, and the
    insurance pays out in the worst states of the world.
  </p>
  <p>
    That doesn't settle whether long horizons make stocks safer, and the critics were right that the price can't see the premium. What it does
    settle is that nobody can remove the long-run shortfall cheaply. If we want to hold more stocks while we're young, we need a reason that
    survives this, and later articles in this section look for one in the wages we haven't earned yet.
