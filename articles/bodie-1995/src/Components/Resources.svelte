  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Bodie, Z. (1995), "On the risk of stocks in the long run", <em>Financial Analysts Journal</em>, 51(3), 18–22. The paper rebuilt here: a
      guarantee against ending behind bonds is a put struck at the forward price, and its cost rises with the horizon.
    </li>
    <li>
      Black, F. and Scholes, M. (1973), "The pricing of options and corporate liabilities", <em>Journal of Political Economy</em>, 81(3),
      637–654; and Merton, R. C. (1973), "Theory of rational option pricing", <em>Bell Journal of Economics and Management Science</em>, 4(1),
      141–183. The pricing model behind the formula.
    </li>
    <li>
      Dempsey, M., Hudson, R., Littler, K. and Keasey, K. (1996), "On the risk of stocks in the long run: a resolution to the debate?",
      <em>Financial Analysts Journal</em>, 52(5). The argument that the put measures the cost of hedging rather than risk.
    </li>
    <li>
      Pástor, Ľ. and Stambaugh, R. F. (2012), "Are stocks really less volatile in the long run?", <em>Journal of Finance</em>, 67(2), 431–478.
      Long-horizon risk once the expected return is uncertain.
    </li>
  </ul>
