  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Miller, M. H. and Modigliani, F. (1961), "Dividend policy, growth, and the valuation of shares", <em>Journal of Business</em>, 34(4),
      411–433. The split of a price into the value of today's earnings and the value of growth opportunities.
    </li>
    <li>
      Gordon, M. J. (1959), "Dividends, earnings, and stock prices", <em>Review of Economics and Statistics</em>, 41(2), 99–105. The growing
      stream of dividends behind the price formula.
    </li>
    <li>
      Ohlson, J. A. (1995), "Earnings, book values, and dividends in equity valuation", <em>Contemporary Accounting Research</em>, 11(2),
      661–687. The residual income model, where the price is book value plus the value of earning more than the required return.
    </li>
    <li>
      Koller, T., Goedhart, M. and Wessels, D., <em>Valuation: Measuring and Managing the Value of Companies</em>, Wiley. Their value driver
      formula is the P/E formula here, written for a whole firm.
    </li>
    <li>
      Damodaran, A., <em>Investment Valuation</em>, Wiley, the chapters on relative valuation and on price-to-book ratios.
    </li>
  </ul>
