  <h3 class="body-header">Growth earns its multiple through the margin</h3>
  <p>
    As we've seen, a firm's P/E rises with growth only when it reinvests at more than its shareholders need. When the return on equity equals the return
    they need, a share is worth the same multiple of its earnings however fast it grows, because the growth costs as much as it's worth. Below
    that, growing lowers the price. The price-to-book ratio carries the same margin more directly, since it sits above 1 whenever the return
    on equity beats the required return.
  </p>
  <p>
    Read backwards, a multiple says less than it seems to. One P/E, even with a P/B beside it, fits a whole line of stories, from a safe firm
    that never grows to a riskier one that grows fast. To tell them apart we need a view on the margin and on how long it can last, and that's
    where most of the work of valuing a company goes.
  </p>
