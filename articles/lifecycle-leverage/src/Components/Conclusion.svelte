  <h3 class="body-header">Spreading the bet</h3>
  <p>
    A saver at 100% stocks carries most of her risk late, when the pile is large, but the load is lumpier than it is lopsided: the last decade
    holds a third of the exposure. Borrowing early and holding less late, at the same total exposure, spreads it more evenly. In our
    simulation a cap of 2 to 1 narrowed the spread of final wealth and lifted the 5th percentile, for a median a little lower.
  </p>
