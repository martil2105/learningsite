  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Ayres, I. and Nalebuff, B. (2010), <em>Lifecycle Investing: A New, Safe, and Audacious Way to Improve the Performance of Your
      Retirement Portfolio</em>, Basic Books. The book that argues a young saver should borrow to hold stocks, and sell down as the pile grows.
    </li>
    <li>
      Ayres, I. and Nalebuff, B. (2008), "Life-cycle investing and leverage: buying stock on margin can reduce retirement risk", NBER Working
      Paper 14094. The first version of the argument, on which the later paper and the book build.
    </li>
    <li>
      Ayres, I. and Nalebuff, B. (2013), "Diversification across time", <em>Journal of Portfolio Management</em>, 39(2), 73–86. The same idea
      in a short paper, tested on US returns since 1871.
    </li>
  </ul>
  <p>Related articles on this site:</p>
  <ul class="resources-list">
    <li><a href="../time-diversification/">Time diversification</a>, on whether stocks get safer the longer we hold them, which is a different claim from this one.</li>
    <li><a href="../human-capital/">Human capital</a>, which reaches a young saver's borrowing from another direction, by counting future pay as part of what we own.</li>
    <li><a href="../cost-of-leverage/">The cost of leverage</a>, on what changes when the loan costs more than the safe rate.</li>
  </ul>
