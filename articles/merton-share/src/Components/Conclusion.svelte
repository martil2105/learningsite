  <h3 class="body-header">One fraction and its fine print</h3>
  <p>
    The Merton share says to hold the premium divided by the variance, scaled down by how much we dislike risk. With a 5-point premium, 18%
    volatility and a risk aversion of 2, that's about three quarters of our savings, whatever our age. The curve around it is forgiving.
    Being a third away from the share costs us about a ninth of the gain, and only being twice as high loses all of it.
  </p>
  <p>
    The weak spot is the premium. Its estimate is blurry enough that an investor with a few decades of data gives away a large part of the
    gain, and with about thirteen years, all of it. The next article asks why the horizon drops out of the formula, and what has to change for
    it to come back in.
  </p>
