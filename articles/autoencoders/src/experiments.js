/*
  What the page reads.

  The HOOK is live: one node's worth of arithmetic on 180 two-dimensional
  points, a few milliseconds a frame, because the reader is dragging a vector
  through it and running gradient descent by hand.

  The SWEEPS come from src/precomputed.js, generated by scripts/precompute.mjs
  from these same modules - twenty-five thousand gradient steps, twice, is fifty
  seconds and not something to do while the page paints. The freshness of that
  file is the first thing verify/check-numbers.mjs checks.
*/
