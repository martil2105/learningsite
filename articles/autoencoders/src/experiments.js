// Loss for a decoder pointing at `deg`, with the encoder either solved in
// closed form or left as given. Cheap enough to call on every pointer move.
export function lossAtAngle(deg, len = 1, solved = true, w1 = null) {
  const th = (deg * Math.PI) / 180;
  const W2 = [[len * Math.cos(th)], [len * Math.sin(th)]];
  const W1 = solved ? optimalEncoder(W2) : w1;
  return aeLoss(PLANE, W1, W2);
}

// The whole loss curve, for the dial under the hook.
export const ANGLE_CURVE = (() => {
  const out = [];
  for (let deg = 0; deg < 180; deg += 1) out.push({ deg, loss: lossAtAngle(deg) });
  return out;
})();
export const WORST_ANGLE_LOSS = Math.max(...ANGLE_CURVE.map((p) => p.loss));

