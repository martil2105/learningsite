// The step at which the loss has stopped moving to four decimals - the moment
// the two stories separate.
export const SETTLED_STEP = (() => {
  const rows = TRACE_FREE.rows;
  const final = rows[rows.length - 1].loss;
  const hit = rows.find((r) => Math.abs(r.loss - final) < 5e-5);
  return hit ? hit.step : rows[rows.length - 1].step;
})();
export const FROZEN_ANGLE = TRACE_FREE.rows[TRACE_FREE.rows.length - 1].angle1;
export const REG_FINAL_ANGLE = TRACE_REG.rows[TRACE_REG.rows.length - 1].angle1;
// Where the regularised run's basis actually swings into place.
export const ROTATION_STEP = (() => {
  const hit = TRACE_REG.rows.find((r) => r.angle1 < 1);
  return hit ? hit.step : null;
})();

