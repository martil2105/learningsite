// The line the linear autoencoder settles on, for drawing.
export const ARC_LINE = (() => {
  const v = P.arc.linearDirection;
  const n = Math.hypot(v[0], v[1]);
  return [v[0] / n, v[1] / n];
})();
export const ARC_LINEAR_RECON = (() => {
  const u = ARC_LINE;
  return ARC.map((x) => {
    const t = x[0] * u[0] + x[1] * u[1];
    return [u[0] * t, u[1] * t];
  });
})();

