  <h3 class="body-header">A record, not a law</h3>
  <p>
    A long record of stock returns feels like evidence about stocks in general. When the record belongs to the market that did best, part of
    what it shows is luck, and luck in the growth rate compounds over a long horizon just as the growth rate does. In our world of identical
    markets, the winner's record understated the chance of a thirty-year real loss by a factor of about eight.
  </p>
  <p>
    Anarkulova, Cederburg and O'Doherty found a gap of much the same size in real data, and a thirty-year loss chance of about one in eight
    once we stop looking only at the winner. Stocks still beat bonds and bills in their data, so the lesson isn't to avoid them. It's that a
    long horizon doesn't make them safe, and that holding many countries' markets helps more than holding one of them for longer.
