  <h3 class="body-header">Where this leaves the average</h3>
  <p>
    Compound growth turns small differences in growth rates into large
    differences in living standards, and the rule of 70 is a good guide to how
    quickly. What the rule asks us to assume, though, is that growth is steady.
  </p>
  <p>
    Once growth swings, the rate an economy actually grows at falls below its
    average growth rate by roughly half the variance, and the expected path and
    the typical one drift apart for ever. For a whole country, that gap is
    small. For a household, a firm or a portfolio, it can be the whole story.
