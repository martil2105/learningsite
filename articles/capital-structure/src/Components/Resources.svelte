  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Modigliani, F. and Miller, M. H. (1958), "The cost of capital, corporation finance and the theory of investment", <em>American Economic
      Review</em>, 48(3), 261–297. Both propositions, and the argument that a firm's value doesn't depend on how it's funded.
    </li>
    <li>
      Modigliani, F. and Miller, M. H. (1963), "Corporate income taxes and the cost of capital: a correction", <em>American Economic
      Review</em>, 53(3), 433–443. The tax saving on a permanent loan.
    </li>
    <li>
      Merton, R. C. (1974), "On the pricing of corporate debt: the risk structure of interest rates", <em>Journal of Finance</em>, 29(2),
      449–470. Shares as a call option on the firm's assets, and risky debt priced from it.
    </li>
    <li>
      Miles, J. A. and Ezzell, J. R. (1980), "The weighted average cost of capital, perfect capital markets, and project life: a
      clarification", <em>Journal of Financial and Quantitative Analysis</em>, 15(3), 719–730. The tax saving when debt is kept at a fixed
      share of value; our version adjusts the loan continuously.
    </li>
    <li>
      Miller, M. H. (1977), "Debt and taxes", <em>Journal of Finance</em>, 32(2), 261–275. How investors' taxes take back part of the
      firm's saving.
    </li>
    <li>
      Brealey, R. A., Myers, S. C. and Allen, F., <em>Principles of Corporate Finance</em>, McGraw-Hill, the chapters on capital structure
      and on the cost of debt.
    </li>
  </ul>
