  <h3 class="body-header">Borrowing moves risk around</h3>
  <p>
    Before tax, borrowing doesn't make a firm any cheaper to fund. It moves risk from one group of investors to another, and each group asks
    to be paid for what it holds, so the cost of capital stays where the assets put it. Shareholders' expected return climbs Modigliani and
    Miller's straight line while the loan is safe, and it bends below that line once lenders start to share the risk.
  </p>
  <p>
    Two details matter when we put numbers on it. A bond's yield is a promise, so using it as the cost of debt makes borrowing look costlier
    than it is. And the value that debt does add, through taxes, depends on how long the loan is meant to stay.
