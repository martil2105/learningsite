  <h3 class="body-header">Same wealth, different wrapping</h3>
  <p>
    At a fair price, a buyback is a dividend in a different wrapper. Earnings per share rise after one and fall after the other, but every
    shareholder ends up with the same wealth, and the P/E lands in the same place. A buyback raises EPS whenever the earnings yield beats
    what the cash would have earned after tax. That says more about interest rates than about value, and the return the share needs rises
    by as much as its earnings do.
  </p>
  <p>
    The difference that matters before tax is the price. A buyback at the wrong price is a dividend plus a trade between the shareholders
    who sell and the ones who stay. So it's worth asking who knows more about what the shares are worth, the firm or the shareholders who
    sell.
