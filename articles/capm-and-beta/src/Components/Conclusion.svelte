  <h3 class="body-header">A flat line, measured fairly</h3>
  <p>
    The CAPM's prediction is a straight line from zero through the market. Testing it with betas estimated from past returns flattens that
    line even in a world where it holds, because sorting on a noisy estimate collects luck as well as risk, and the luck fades. In US data
    the groups sorted at betas from 0.22 to 2.66 went on to have betas from 0.59 to 1.60, and a line drawn against the sorting betas would
    have shown us mostly the ruler.
  </p>
  <p>
    Measured against the betas the groups actually had, the US line is still about half as steep as the CAPM says, and the low-beta groups
    keep a positive alpha. So the flat line isn't only a measurement problem, and that's what makes it worth explaining.
  </p>
