  <h3 class="body-header">A long run, and a bumpy one</h3>
  <p>
    Kelly's rule picks the bet that makes our money grow fastest, and in the long run nothing beats it. What the rule doesn't say is how long
    the long run is. That's set by the Sharpe ratio of the bet, so a good coin gets there in a few hundred flips, while the stock market needs
    lifetimes.
  </p>
  <p>
    The ride there is rough as well. At full Kelly, the chance of ever falling to any share of our money is that share, so we should expect to
    see our savings halve at some point. Half Kelly gives up a quarter of the growth and takes away most of that pain, which is why so many
    people who take Kelly seriously bet less than it says.
  </p>
