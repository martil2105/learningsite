  <ul class="resources-list">
    <li>
      Gordon, H. S. (1954), "The Economic Theory of a Common-Property Resource:
      The Fishery", <em>Journal of Political Economy</em>, 62(2), 124–142. The
      paper that showed open access pushes fishing on until the average catch
      equals the cost of the time, so the rent is used up.
    </li>
    <li>
      Hardin, G. (1968), "The Tragedy of the Commons", <em>Science</em>,
      162(3859), 1243–1248. The essay that gave the problem its name.
    </li>
    <li>
      Ostrom, E. (1990), <em>Governing the Commons: The Evolution of
      Institutions for Collective Action</em>, Cambridge University Press. How
      real communities manage shared resources with rules of their own,
      without a single owner or a state fee.
    </li>
  </ul>
