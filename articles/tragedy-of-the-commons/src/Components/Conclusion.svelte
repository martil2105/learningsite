  <h3 class="body-header">Where this leaves the commons</h3>
  <p>
    The tragedy of the commons is often told as a story about greed, or about
    crowds. Our lake tells it as a question of what each user counts. An owner
    stops where the last hour's catch pays for its time. A boat on a shared
    lake counts mostly the average catch, which stays above the wage long
    after the owner would have stopped. So the boat keeps fishing after the
    extra hours have stopped paying for the lake as a whole.
  </p>
  <p>
    That's also why a few users do so much of the damage. Most of the rent is
    gone before the lake is anything like crowded, so if a shared resource
    needs rules or a fee, it needs them early, while there are still only a
    few people using it.
