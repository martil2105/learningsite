  <h3 class="body-header">A kink at 100%</h3>
  <p>
    When borrowing costs more than the safe rate, Merton's line splits at 100% in stocks. Savers who would borrow at the safe rate borrow less,
    and a band of them, wider with every point of spread, stops at exactly 100%. For a young saver counting on future pay the spread bites
    twice, once on the share and once on the value of the pay. At a spread of 2 points it takes more than half of the leverage the human
    capital article asked for.
  </p>
  <p>
    The size of the spread is most of the question. It's small for those who borrow through futures and large for households, which is a
    reason to ask where a plan's loan would come from before asking how much to borrow.
