  <h3 class="body-header">Why the wage stays high</h3>
  <p>
    Once a wage buys effort as well as hours, the firm's problem changes. It's
    no longer looking for the lowest wage anyone will accept, but for the
    cheapest effort, and that sits where a 1% pay rise buys 1% more effort. How
    many workers the firm wants doesn't come into it.
  </p>
  <p>
    That turns the usual picture around. The people who'd work for less aren't
    a sign that the market has failed to clear. In the monitoring story,
    they're what gives the higher wage its force, because losing a well-paid
    job only hurts when there isn't another one waiting. So when you see a
    queue for jobs that pay well, it's worth asking what the wage is buying.
