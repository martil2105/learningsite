  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      CORE Econ (2023), <em>The Economy 2.0: Microeconomics</em>, Unit 6. A
      free introduction to the wage as an incentive and to employment rents.
    </li>
    <li>
      Solow, R. M. (1979), "Another Possible Source of Wage Stickiness",
      <em>Journal of Macroeconomics</em>, 1(1), 79–82. The condition that the
      elasticity of effort with respect to the wage is one.
    </li>
    <li>
      Shapiro, C. and Stiglitz, J. E. (1984), "Equilibrium Unemployment as a
      Worker Discipline Device", <em>American Economic Review</em>, 74(3),
      433–444. The monitoring story, and the queue as the thing that makes
      being fired costly.
    </li>
    <li>
      Akerlof, G. A. and Yellen, J. L. (1990), "The Fair Wage-Effort
      Hypothesis and Unemployment", <em>Quarterly Journal of Economics</em>,
      105(2), 255–283. The fair-wage reading, in which people work harder when
      they feel fairly paid.
    </li>
  </ul>
