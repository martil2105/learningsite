/*
  What the page reads.

  Two sources, and the split between them is deliberate:

    - the HOOK is computed here, eagerly, on load. It is one node, one feature,
      one pass over 6,000 rows per bin setting: a couple of milliseconds, and
      the reader is dragging a slider through it, so it has to be live.

    - the SWEEPS come from src/precomputed.js, generated by
      scripts/precompute.mjs from these same modules. Twelve boosted forests is
      about five seconds of work, which is not something to do while the reader
      waits for the page to paint. verify/check-numbers.mjs re-runs every one of
      those fits and fails if the committed numbers have moved, so the file
      cannot quietly go stale.
*/
import P from "./precomputed.js";
import { FEATURES, TRAIN_COLS, TRAIN_Y, N_TRAIN, NEEDLE_TRAIN, NEEDLE_LO, NEEDLE_HI, NEEDLE_WIDTH, column } from "./datasets.js";
import {
  binEdges, binizeColumn, newHistogram, buildHistogram, histogramBestSplit,
  exactGainCurve, argsortIndices, splitGain, bytesPerValue, resetCounters,
} from "./binning.js";

export const PRE = P;
export const CONFIG = P.config;
export const BIN_SETTINGS = P.BIN_SETTINGS;

/* ------------------------------------------------------------- the hook
   The root of the first tree. With squared error and a constant initial
   prediction, the gradient of row i is (mean(y) - y_i) and every hessian is 1,
   so this is the first split any of these models makes.
*/
export const HOOK_FEATURE = 0; // distance
const values = TRAIN_COLS[HOOK_FEATURE];
const ybar = TRAIN_Y.reduce((a, b) => a + b, 0) / N_TRAIN;
const grad = Float64Array.from(TRAIN_Y, (y) => ybar - y);
const hess = new Float64Array(N_TRAIN).fill(1);
const order = argsortIndices(values);
const SPLIT_PARAMS = { lambda: CONFIG.lambda, gamma: CONFIG.gamma, minDataInLeaf: CONFIG.minDataInLeaf };

// Counters are the article's cost model; the hook must not pollute them.
resetCounters();

export const EXACT_CURVE = exactGainCurve(values, order, grad, hess, SPLIT_PARAMS);
export const EXACT_BEST = EXACT_CURVE.reduce((a, b) => (b.gain > a.gain ? b : a));
export const X_RANGE = [values[order[0]], values[order[order.length - 1]]];

/*
  Every bin setting the slider offers, evaluated once. Each is one pass over the
  column to bin it, one pass to accumulate the histogram, and a scan of at most
  254 boundaries - so all eight together cost less than drawing the chart does.
*/
export const BINNED = BIN_SETTINGS.map((maxBin) => {
  const edges = binEdges(values, maxBin, { minDataInBin: CONFIG.minDataInBin });
  const binned = binizeColumn(values, edges);
  const hist = newHistogram(edges.length + 1);
  buildHistogram(hist, binned, Int32Array.from({ length: N_TRAIN }, (_, i) => i), grad, hess);
  const best = histogramBestSplit(hist, SPLIT_PARAMS);
  // Every bin boundary the scan considered, with its gain, so the chart can
  // draw the candidates rather than only the winner.
  const candidates = [];
  let gL = 0;
  let hL = 0;
  let cL = 0;
  let G = 0;
  let H = 0;
  let C = 0;
  for (let b = 0; b < hist.g.length; b++) {
    G += hist.g[b];
    H += hist.h[b];
    C += hist.c[b];
  }
  for (let b = 0; b < hist.g.length - 1; b++) {
    gL += hist.g[b];
    hL += hist.h[b];
    cL += hist.c[b];
    if (cL < CONFIG.minDataInLeaf || C - cL < CONFIG.minDataInLeaf) continue;
    const gain =
      0.5 * ((gL * gL) / (hL + CONFIG.lambda) + ((G - gL) * (G - gL)) / (H - hL + CONFIG.lambda) - (G * G) / (H + CONFIG.lambda)) -
      CONFIG.gamma;
    candidates.push({ threshold: edges[b], gain, bin: b, countLeft: cL });
  }
  resetCounters();
  return {
    maxBin,
    edges,
    nBins: edges.length + 1,
    counts: Array.from(hist.c),
    candidates,
    best: best ? { ...best, threshold: edges[best.bin] } : null,
    bytesPerValue: bytesPerValue(edges.length + 1),
  };
});

export const kept = (b) => (b.best ? b.best.gain / EXACT_BEST.gain : 0);

/* --------------------------------------------------------- the cost model */
export const SPLIT_TRACE = P.splitTrace;
export const N_SPLITS = P.splitTrace.length;
export const SPLITS_BELOW_BINS = P.splitTrace.filter((s) => s.nodeSize < 255).length;
export const SUM_NODE_ROWS = P.splitTrace.reduce((a, s) => a + s.nodeSize, 0);
export const SUM_SMALLER_ROWS = P.splitTrace.reduce((a, s) => a + s.smaller, 0);
export const SUBTRACT_SAVING = 1 - P.hist.rowTouches / P.histNoSubtract.rowTouches;

export const GAIN_EVAL_RATIO = P.exact.gainEvals / P.hist.gainEvals;
export const ROW_TOUCH_RATIO = P.exact.rowTouches / P.hist.rowTouches;
export const NOSUB_VS_EXACT = P.histNoSubtract.rowTouches / P.exact.rowTouches;
export const ACCURACY_COST = (P.hist.test - P.exact.test) / P.exact.test;

/* ------------------------------------------------------------- the sweeps */
export const BIN_SWEEP = P.binSweep.map((r) => ({ ...r, excess: (r.test - P.exact.test) / P.exact.test }));
export const LEAF_FLOOR = P.leafFloor.map((r) => ({
  ...r,
  bins: r.bins.map((b) => ({ ...b, excess: (b.test - r.exact) / r.exact })),
}));
export const FLOOR_BINS = P.FLOOR_BINS;
// The coarsest bin count that stays within `tol` of the exact model, per floor.
export const firstWithin = (row, tol = 0.03) => {
  const hit = row.bins.find((b) => b.excess < tol);
  return hit ? hit.maxBin : null;
};

export const NEEDLE = P.needle;
export const NEEDLE_INFO = { lo: NEEDLE_LO, hi: NEEDLE_HI, width: NEEDLE_WIDTH, n: NEEDLE_TRAIN.length };
export const NEEDLE_X = column(NEEDLE_TRAIN, 0);
export const NEEDLE_Y = Float64Array.from(NEEDLE_TRAIN, (r) => r.y);
export const EDGE_SETS = P.edgeSets;

/*
  Edge sets the figures draw directly. Cheap - one sort and a walk per call -
  and computed here rather than in the components so that the check script sees
  exactly the arrays the page draws.
*/
export const NEEDLE_EDGES = Object.fromEntries(
  [8, 255].map((b) => [b, binEdges(NEEDLE_X, b, { minDataInBin: CONFIG.minDataInBin })])
);
export const NEEDLE_ROW = (b) => NEEDLE.rows.find((r) => r.maxBin === b);
export const DISTANCE_EDGES = Object.fromEntries(
  [8, 32, 255].map((b) => [b, binEdges(TRAIN_COLS[HOOK_FEATURE], b, { minDataInBin: CONFIG.minDataInBin })])
);
export const STOPS = P.edgeSets.find((e) => e.key === "stops");
export const HOUR = P.edgeSets.find((e) => e.key === "hour");

/* ------------------------------------------------------------- formatting */
export const int = (x) => Math.round(x).toLocaleString("en-US");
export const big = (x) =>
  x >= 1e6 ? (x / 1e6).toFixed(2) + " million" : x >= 1e3 ? (x / 1e3).toFixed(0) + ",000" : String(Math.round(x));
export const compact = (x) => (x >= 1e6 ? (x / 1e6).toFixed(2) + "M" : x >= 1e3 ? (x / 1e3).toFixed(0) + "k" : String(Math.round(x)));
export const pct = (x, d = 0) => (100 * x).toFixed(d) + "%";
export const times = (x) => x.toFixed(1) + "×";
export const rmse = (x) => x.toFixed(2);
