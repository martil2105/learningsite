  <h3 class="body-header">A rate and an amount</h3>
  <p>
    The IRR and the NPV answer different questions. The IRR is a rate, the return a project earns on our money while it's tied up, and the NPV
    is an amount, how much richer the project makes us today. Hazen's identity connects them: the NPV is the IRR's margin over the cost of
    capital, times the money the project keeps tied up. So the IRR ranks projects by height and the NPV by area, and when a quick, small
    project beats a slow or large one on IRR, it's because it ties up less money for less time.
  </p>
  <p>
    The same identity explains the stranger cases. Where two NPV curves cross, the rectangles have the same area. And when a project has two
    IRRs, each one balances its own account, so if that account is mostly a loan to us, a high IRR is a high interest rate that we're paying.
  </p>
