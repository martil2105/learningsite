  <h3 class="body-header">A share is an option</h3>
  <p>
    Merton's model treats a firm's shares as a call option on its assets, struck at its debt. Read backwards, that turns two things we can
    see, the share price and how much it moves, into two things we can't, what the assets are worth and how risky they are. From there it's
    one step to the distance to default and a probability.
  </p>
  <p>
    The probability that comes out is the market's, the one that prices the firm's shares and debt. It sits a fixed distance from the real chance on the normal curve, set by the Sharpe ratio and the square root of time. So it overstates the real chance most for the safest firms and the longest loans. Our model's simplifications push its real chances too low as well: one loan, default only on the day it's due, and normal tails. That's why the people who sell these numbers calibrate them to defaults they've actually seen.
  </p>
