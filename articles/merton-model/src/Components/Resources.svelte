  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Merton, R. C. (1974), "On the pricing of corporate debt: the risk structure of interest rates", <em>Journal of Finance</em>, 29(2),
      449–470. The shares as a call on the assets.
    </li>
    <li>
      Black, F. and Scholes, M. (1973), "The pricing of options and corporate liabilities", <em>Journal of Political Economy</em>, 81(3),
      637–654.
    </li>
    <li>
      Black, F. and Cox, J. C. (1976), "Valuing corporate securities: some effects of bond indenture provisions", <em>Journal of Finance</em>,
      31(2), 351–367. Default the first time the assets touch a line.
    </li>
    <li>
      Black, F. (1976), "Studies of stock price volatility changes", <em>Proceedings of the 1976 Meetings of the American Statistical
      Association, Business and Economic Statistics Section</em>, 177–181. The leverage effect.
    </li>
    <li>
      Crosbie, P. and Bohn, J. (2003), <em>Modeling Default Risk</em>, Moody's KMV. The distance to default in practice: the default point and
      the lookup from distance to default rate.
    </li>
    <li>
      Chen, L., Collin-Dufresne, P. and Goldstein, R. S. (2009), "On the relation between the credit spread puzzle and the equity premium
      puzzle", <em>Review of Financial Studies</em>, 22(9), 3367–3409. The source of the 45 cents, Moody's average recovery on senior
      unsecured bonds.
    </li>
    <li>
      Bharath, S. T. and Shumway, T. (2008), "Forecasting default with the Merton distance to default model", <em>Review of Financial
      Studies</em>, 21(3), 1339–1369.
    </li>
