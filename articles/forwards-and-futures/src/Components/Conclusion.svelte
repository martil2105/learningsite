  <h3 class="body-header">What a forward price measures</h3>
  <p>
    A forward price is what it costs to buy something now and hold it until delivery: interest, minus anything it pays, plus anything it
    costs to store. For anything that can be bought, stored and lent, an arbitrage pins the price there from both sides, and it does so
    whatever anyone expects. Someone who buys forward still expects to earn the asset's risk premium, but the price itself isn't a forecast.
  </p>
  <p>
    For something that can be stored but not lent, the cost of carry is only a ceiling. Below it sits the value of having the thing now, which can push the forward price below today's. When storage runs short, the ceiling itself shoots up, which is how we got oil for June costing $58.06 more than oil for May. Futures add daily settlement, and with a tailed position they match a forward exactly.
  </p>
