  <h3 class="body-header">Where this leaves the formula</h3>
  <p>
    The spending formula is right, and so is its minus sign, as long as we read
    the sign as bookkeeping rather than economics. An import changes GDP only
    through the home production it displaces. That can be anywhere from none of
    its value to all of it, and the trade line in a release reads the same
    across that whole range.
  </p>
  <p>
    So the next time we read that trade subtracted a point from growth, the
    useful question is what the imports replaced. The answer is in the other
    lines of the table, not in that one.
