  <h3 class="body-header">Adding risks isn't spreading them</h3>
  <p>
    Samuelson's colleague wanted the comfort of the law of large numbers, which settles the average result per bet, while taking on the total,
    which it doesn't settle. If a bet is bad for us at every wealth we might pass through, then a run of them is bad for us too. For a person with
    constant risk aversion, a hundred bets are worth a hundred times one.
  </p>
  <p>
    Later work didn't overturn the theorem. It moved the argument to the premise, which is strong, and to the colleague, whose answers make sense
    if he's loss averse and judges the whole run at once. For investors the lesson carries over: more years in the market pile up risk rather
    than spread it, and the next article prices that risk directly.
