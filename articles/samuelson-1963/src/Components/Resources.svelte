  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Samuelson, P. A. (1963), "Risk and uncertainty: a fallacy of large numbers", <em>Scientia</em>, 98, 108–113. The paper rebuilt here, and
      the source of the bet and the theorem.
    </li>
    <li>
      Samuelson, P. A. (1969), "Lifetime portfolio selection by dynamic stochastic programming", <em>Review of Economics and Statistics</em>,
      51(3), 239–246. The horizon result for investors.
    </li>
    <li>
      Rabin, M. (2000), "Risk aversion and expected-utility theory: a calibration theorem", <em>Econometrica</em>, 68(5), 1281–1292. What
      refusing small bets at every wealth level implies for large ones.
    </li>
    <li>
      Ross, S. A. (1999), "Adding risks: Samuelson's fallacy of large numbers revisited", <em>Journal of Financial and Quantitative
      Analysis</em>, 34(3), 323–339. When accepting a run of favourable bets is consistent with expected utility.
    </li>
    <li>
      Benartzi, S. and Thaler, R. H. (1999), "Risk aversion or myopia? Choices in repeated gambles and retirement investments",
      <em>Management Science</em>, 45(3), 364–381. Experiments on repeated gambles and on showing people the combined distribution.
    </li>
    <li>
      Benartzi, S. and Thaler, R. H. (1995), "Myopic loss aversion and the equity premium puzzle", <em>Quarterly Journal of Economics</em>,
      110(1), 73–92. Loss aversion with frequent evaluation, applied to stocks.
    </li>
    <li>
      Tversky, A. and Kahneman, D. (1992), "Advances in prospect theory: cumulative representation of uncertainty", <em>Journal of Risk and
      Uncertainty</em>, 5(4), 297–323. The estimate of 2.25 for how much more losses weigh than gains.
    </li>
  </ul>
