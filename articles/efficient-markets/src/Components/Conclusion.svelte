  <h3 class="body-header">Predictable isn't profitable</h3>
  <p>
    An efficient market says tomorrow's change in a price can't be predicted from what we know today, and the variance ratio is a clean way to
    check. But the test only sees the prices that were written down. When those are stale, or bounce between the bid and the ask, they fail the
    test while the price anyone could actually trade at is still a random walk.
  </p>
  <p>
    That's why a rejection is the start of the question rather than the answer. Before a pattern in returns becomes a strategy, it's worth
    asking whether we could have traded at the prices that made it, and what it would have cost.
  </p>
