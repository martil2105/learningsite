  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      CORE Econ (2023), <em>The Economy 2.0: Microeconomics</em>, Unit 3 and its
      mathematical Extension. A free introduction to the worker's choice between
      consumption and free time, in the form we've used here.
    </li>
    <li>
      Robbins, L. (1930), "On the Elasticity of Demand for Income in Terms of
      Effort", <em>Economica</em> 29, 123–129. Robbins was answering Pigou and
      Knight, who held that higher wages must reduce effort, and his conclusion
      is the one still taught: we can't say in advance, so we have to measure
      the elasticity for the workers concerned. He's right that the model
      doesn't settle it in general. What this page adds is that choosing the
      function settles it before any data is consulted.
    </li>
    <li>
      Arrow, K. J., Chenery, H. B., Minhas, B. S. and Solow, R. M. (1961),
      "Capital–Labor Substitution and Economic Efficiency", <em>Review of
      Economics and Statistics</em> 43, 225–250. Where the CES form comes from.
    </li>
    <li>
      Geary, R. C. (1950), "A Note on 'A Constant-Utility Index of the Cost of
      Living'", <em>Review of Economic Studies</em>, 18(1), 65–66, and Stone, R.
      (1954), "Linear Expenditure Systems and Demand Analysis: An Application
      to the Pattern of British Demand", <em>Economic Journal</em>, 64(255),
      511–527. The source of the subsistence term. The two are usually met
      together as the linear expenditure system.
    </li>
  </ul>
