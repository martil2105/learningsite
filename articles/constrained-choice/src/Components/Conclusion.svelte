  <h3 class="body-header">What the diagram had already decided</h3>
  <p>
    First courses are right that, in general, theory can't tell us whether a
    pay rise makes people work more or less. What we've seen is that the
    diagram usually drawn beside that answer has already made the choice. With
    Cobb–Douglas preferences, the two effects cancel and hours don't move, and
    across the wider CES family, it's σ that decides which way they go.
  </p>
  <p>
    What carries over to other problems is the method. We write down the constraint,
    write down the preference and find where the rates agree. Then comes the
    step that is easy to skip, which is to check whether the answer depends on an
    assumption we weren't paying attention to. Here, it depended on one
    entirely.
  </p>
