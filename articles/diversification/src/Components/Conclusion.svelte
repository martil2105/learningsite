  <h3 class="body-header">More than comfort</h3>
  <p>
    Holding more stocks shrinks a portfolio's variance towards the average covariance between them. The part above that floor falls like one over the number of stocks, so a handful of stocks already removes most of what can be removed. That's the part of diversification that everyone expects.
  </p>
  <p>
    The part that's easy to miss is growth. Our expected return stays where it was, but the rate our money compounds at rises by half the variance we removed. Over a few decades that's enough for most single stocks to
    finish behind the portfolio they belong to. Equal weights were a choice we
    made for simplicity, and the next article asks whether some other set of
    weights could do better.
