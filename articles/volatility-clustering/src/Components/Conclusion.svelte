  <h3 class="body-header">Calm and storm</h3>
  <p>
    The direction of the market's next move is close to a coin toss, but its size isn't. Big days come in clusters, and the memory fades
    over months rather than days, which is enough for a simple forecast to track how wide the next day's moves are likely to be.
  </p>
  <p>
    Measuring each day against that forecast changes which days look extreme. Some of the famous crashes turn out to be ordinary days in
    extraordinary weeks, and the real surprises are the falls that came out of a calm market. What's left over is still fat-tailed, so a
    good model of risk needs both the clustering and the tails.
