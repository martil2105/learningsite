  <h3 class="body-header">Where this leaves monopolistic competition</h3>
  <p>
    Dixit and Stiglitz's model gives us a clean account of a market full of
    varieties. Each firm has a little power over its price, entry keeps profit
    at zero, and the market ends up with slightly more varieties than a planner
    would choose.
  </p>
  <p>
    Keeping the number of firms finite adds three corrections that the
    large-group version leaves out. The elasticity each firm faces is
    σ − (σ − 1)/n rather than σ, each firm makes 1/n less than the large-group
    scale, and the extra varieties never add up to a whole firm. All three fade
    as the market grows, which is why the large-group results are a good guide
    to big markets and a slightly rosy one to small markets.
  </p>
