  <h3 class="body-header">Hours as insurance</h3>
  <p>
    Bodie, Merton and Samuelson's point is that our hours are an asset we can spend after a loss. A worker who can change them pays for a bad
    year partly in leisure, so her consumption swings less than a fixed worker's, and she can afford to hold more stock to begin with. In our
    version of the problem that comes to a single factor, set by how much we care about consumption and how much we dislike risk.
  </p>
  <p>
    What flexibility doesn't change is the size of the bet compared with everything we own. It changes who pays when the bet goes wrong.
