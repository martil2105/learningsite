  <h3 class="body-header">A spread that passes money along</h3>
  <p>
    In Glosten and Milgrom's market the spread isn't the market maker's income. It's the price of trading with people who might know
    more, set so the market maker breaks even, and it moves money from the traders who don't know to the ones who do. It's widest when
    the market maker is least sure, and it closes as each trade teaches the price a little.
  </p>
  <p>
    A smaller informed share makes each trade cheaper and each piece of news dearer, because the price learns four times more slowly for
    every halving. Whether a narrow spread is good news for the uninformed depends on how long they have to keep paying it.
