  <h3 class="body-header">Where this leaves the rate</h3>
  <p>
    The unemployment rate is a useful number, and it's the right one for asking
    how many people are out of work right now. But where it settles is set by
    the ratio of two flows, so it can't tell a churning labour market from a
    stagnant one, or a wave of layoffs from a hiring freeze.
  </p>
  <p>
    Nor can it tell us whether the people it counts have been looking for two
    months or two years. For questions like those, we need the flows
    themselves. So when you see the rate move, the question to ask is which of
    the two flows moved it.
  </p>
