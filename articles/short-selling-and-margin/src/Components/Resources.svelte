  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      Board of Governors of the Federal Reserve System, Regulation T, "Credit by brokers and dealers" (12 CFR Part 220). The 50% initial
      margin for buying on margin and for short sales.
    </li>
    <li>
      FINRA Rule 4210, "Margin requirements". The maintenance margins: 25% of the value of a long position, and for a short in a stock
      priced at $5 or more, 30% of its value or $5 a share, whichever is greater.
    </li>
    <li>
      Brunnermeier, M. K. and Pedersen, L. H. (2009), "Market liquidity and funding liquidity", <em>Review of Financial Studies</em>, 22(6),
      2201–2238. How margin requirements and forced selling feed on each other.
    </li>
    <li>
      D'Avolio, G. (2002), "The market for borrowing stock", <em>Journal of Financial Economics</em>, 66(2–3), 271–306. What it costs to
      borrow shares, and how often lenders recall them.
    </li>
    <li>
      Shreve, S. E. (2004), <em>Stochastic Calculus for Finance II: Continuous-Time Models</em>, Springer, section 3.7. The reflection
      principle behind the chance of a call.
    </li>
  </ul>
