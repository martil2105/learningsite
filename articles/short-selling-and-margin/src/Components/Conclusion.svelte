  <h3 class="body-header">Leverage that drifts</h3>
  <p>
    A margin account's leverage is where we start, not where we stay. It rises as the trade goes against us, and the broker calls when it
    reaches one over the maintenance margin. That's why a long bought with half its price borrowed is called after a fall of a third, with
    two thirds of our own money already gone.
  </p>
  <p>
    A short is called far sooner, after a rise of about 15% under the usual rules, because its position grows as it loses. Measured the way
    prices move, the short's call is almost three times closer, and over a year at 30% volatility it comes nearly two times in three.
