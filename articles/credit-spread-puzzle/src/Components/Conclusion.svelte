  <h3 class="body-header">Several times, and why</h3>
  <p>
    For a century, Baa bonds have paid more than four times as much over Aaa bonds as their extra defaults cost. That's less puzzling than it sounds.
    Lenders are paid with the market's chance of default, which is higher than the real one because defaults come in bad times, and a model
    built on that explains most of the gap. It also predicts that the safest bonds should pay the biggest multiples of their expected losses.
  </p>
  <p>
    What's left is smaller and harder to pin down. It depends on a price of risk that may rise in recessions, and on parts of the spread that have nothing to do with default. It also depends on default rates measured over a few decades in which defaults came in waves. A 32-year record can
    easily be off by half, so the puzzle is partly a puzzle about how little a few decades can tell us.
