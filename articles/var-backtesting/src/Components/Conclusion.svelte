  <h3 class="body-header">How many, and when</h3>
  <p>
    Counting exceptions asks one question: did the bad days come about as often as the model promised? For a 99% value at risk, that's a
    question about two or three rare days a year. That's too few to tell a right model from one that's twice too optimistic. The years of
    data that would settle it are rarely there either, because the model and the book don't stay the same for that long.
  </p>
  <p>
    The bigger gap is the one the count can't see at all. On the US market, a model with exactly the right number of exceptions put most of
    them into a handful of terrible years. A regulator looking one year at a time would have flagged it in those years and waved it through
    in all the others. A good backtest asks when the exceptions came, as well as how many there were.
  </p>
