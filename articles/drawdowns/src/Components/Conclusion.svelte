  <h3 class="body-header">A record, not a limit</h3>
  <p>
    A maximum drawdown is the worst fall in a record, so it keeps growing as the record gets longer. With no edge it grows like the square
    root of the years, and with an edge it slows to a logarithm after about one over the Sharpe ratio squared years. That's why live trading
    goes past a backtest's worst half the time within the backtest's own length, even when nothing has changed.
  </p>
  <p>
    It's also why a deep fall is weak evidence that an edge has gone. A drawdown is mostly volatility, which working and dead strategies share,
    so a line deep enough to spare the working ones lets most of the dead ones through. If we want to know whether the edge is still there,
    the drawdown is the wrong place to look for it.
  </p>
