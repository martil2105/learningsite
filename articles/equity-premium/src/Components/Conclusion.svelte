  <h3 class="body-header">What a century can tell us</h3>
  <p>
    A century of US returns puts the equity premium at about 9% a year, with a band from roughly 5% to 13%. Sampling more often doesn't
    narrow that band, because its width depends on how many years we've watched rather than how many returns we've recorded. Inside the same
    century, thirty-year windows range from under 5% to over 14%.
  </p>
  <p>
    Built from dividends instead, the estimate since 1950 is lower and much tighter. The difference is that prices rose faster than
    dividends, as investors paid more and more for each dollar of them. Neither number is the true premium, but together they tell us how
    much of a famous average came from a repricing that can't keep happening.
