  <h3 class="body-header">Rare, but not that rare</h3>
  <p>
    Days the normal distribution treats as impossible turn up in US stock returns about once a year. Their tails fall like a power law with an
    exponent near 3, so each doubling in size makes a day about eight times rarer, not astronomically rarer.
  </p>
  <p>
    With that exponent the standard deviation is a well-defined number and the kurtosis isn't. A number like "a kurtosis of 19" describes the sample
    we happened to collect, and mostly its worst day, rather than the market itself.
