  <h3 class="body-header">Sources and further reading</h3>
  <ul class="resources-list">
    <li>
      French, K. R., <em>Data Library</em>, Tuck School of Business at Dartmouth: the daily Fama/French research factors (the market's
      return above one-month bills, and the bill return), July 1926 to August 2026, built from the 202608 CRSP database.
    </li>
    <li>
      Mandelbrot, B. (1963), "The variation of certain speculative prices", <em>Journal of Business</em>, 36(4), 394–419. An early and famous look at fat tails in prices.
    </li>
    <li>
      Hill, B. M. (1975), "A simple general approach to inference about the tail of a distribution", <em>Annals of Statistics</em>, 3(5),
      1163–1174. The estimator of the tail exponent.
    </li>
    <li>
      Gopikrishnan, P., Meyer, M., Amaral, L. A. N. and Stanley, H. E. (1998), "Inverse cubic law for the distribution of stock price
      variations", <em>European Physical Journal B</em>, 3(2), 139–140.
    </li>
    <li>
      Cont, R. (2001), "Empirical properties of asset returns: stylized facts and statistical issues", <em>Quantitative Finance</em>, 1(2),
      223–236. Fat tails, thinner tails over longer horizons, and volatility clustering.
    </li>
  </ul>
