  <h3 class="body-header">Where this leaves the envelope</h3>
  <p>
    The long-run cost curve really is the lower envelope of the short-run
    curves, and first courses are right to draw it that way. What the envelope
    doesn't do is touch each short-run curve at its lowest point. It does that
    once, at the bottom of the envelope. Everywhere else, each plant is run a
    little off its own sweet spot, below it for small plants and above it for
    big ones.
  </p>
  <p>
    That isn't a mistake by the firm. It's what choosing a plant by marginal
    cost looks like, and because the envelope is flat, being slightly off costs
    very little. So the next time you see the envelope drawn, it's worth
    checking where the U's touch it.
